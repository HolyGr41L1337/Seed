function pickLanguage() {
  try {
    const stored = localStorage.getItem('seed.lang');
    if (stored === 'zh' || stored === 'en') return stored;
  } catch {
    /* storage unavailable */
  }
  return /^zh\b/i.test(navigator.language || '') ? 'zh' : 'en';
}

export const lang = pickLanguage();
const table = lang === 'zh' ? zh : en;

/** Look up interface text: t('send'), t('retrying', 2), t('commands.new'). */
export function t(key, ...args) {
  let value = table;
  for (const part of key.split('.')) value = value?.[part];
  if (value === undefined) {
    value = en;
    for (const part of key.split('.')) value = value?.[part];
  }
  if (typeof value === 'function') return value(...args);
  return value ?? key;
}

/** For extensions: seed.tr('中文', 'English'). */
export function tr(chinese, english) {
  return lang === 'zh' ? chinese : english;
}
