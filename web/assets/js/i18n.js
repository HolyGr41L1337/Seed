/** Every interface language, by its code. */
export const languages = { zh, en, ja, fr, ru };

/** The language for a browser or system locale such as "ja-JP"; English when there is no table for it. */
export function languageFor(locale) {
  const code = String(locale || '').slice(0, 2).toLowerCase();
  return Object.hasOwn(languages, code) ? code : 'en';
}

function pickLanguage() {
  try {
    const stored = localStorage.getItem('seed.lang');
    if (stored && Object.hasOwn(languages, stored)) return stored;
  } catch {
    /* storage unavailable */
  }
  return languageFor(globalThis.navigator?.language);
}

export const lang = pickLanguage();
const table = languages[lang];

/** Look up interface text: t('send'), t('retrying', 2), t('commands.new'). */
export function t(key, ...args) {
  let value = table;
  for (const part of key.split('.')) value = value?.[part];
  if (value === undefined) {
    value = en;
    for (const part of key.split('.')) value = value?.[part];
  }
  if (typeof value === 'function') return value(...args);
  return value ?? key;
}

/**
 * For extensions: seed.tr('中文', 'English'), or with more languages
 * seed.tr('中文', 'English', { ja: '日本語', fr: 'Français', ru: 'Русский' }).
 * A language without its own text gets the English one.
 */
export function tr(chinese, english, others) {
  if (lang === 'zh') return chinese;
  return others?.[lang] ?? english;
}
